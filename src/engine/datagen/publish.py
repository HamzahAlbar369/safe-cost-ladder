"""Write splits, MANIFEST.json and the dev review file (SPEC §4.2 step 5, §4.4). FICTIONAL data.

The held-out file is written and hashed; its items are never printed or put in any review file.
"""

from __future__ import annotations

import hashlib
import json
import random
from pathlib import Path
from typing import Any

from engine.contracts import AdjudicateGold, Ticket
from engine.datagen import gen as G
from engine.datagen.rules import RULES_V1, RULES_V2
from engine.llm.pricing import ROOT
from engine.runinfo import git_sha

MANIFEST = G.OUT / "MANIFEST.json"
REVIEW = ROOT / "data" / "review" / "dev_review.md"
REVIEW_EN, REVIEW_AR = 30, 20


def serialise(tickets: list[Ticket]) -> bytes:
    return "".join(t.model_dump_json() + "\n" for t in tickets).encode("utf-8")


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def split_path(split: str) -> Path:
    return G.OUT / f"{split}.jsonl"


def build_manifest(
    splits: dict[str, list[Ticket]], qa: dict[str, Any], blobs: dict[str, bytes]
) -> dict[str, Any]:
    return {
        "fiction": "FICTIONAL insurer; synthetic tickets. Rules follow SAMA-issued instruments "
        "(see data/rules/SOURCES.md).",
        "seed": G.SEED,
        "generator_git_sha": git_sha(),
        "rules_sha256": {
            "rules.yaml": sha256(RULES_V1.read_bytes()),
            "rules_v2.yaml": sha256(RULES_V2.read_bytes()),
        },
        "files": {f"{s}.jsonl": {"sha256": sha256(b), "n": len(splits[s])} for s, b in blobs.items()},
        "heldout_sealed": {
            "sha256": sha256(blobs["heldout"]),
            "note": "never read by a person or an LLM; only `engine final` (freeze-* tag) loads it",
        },
        "composition": qa["_composition_table"],
        "decision_distribution": qa["decision_distribution"],
        "qa": {k: v for k, v in qa.items() if not k.startswith("_") and k != "decision_distribution"},
    }


def write(splits: dict[str, list[Ticket]], qa: dict[str, Any]) -> dict[str, Any]:
    G.OUT.mkdir(parents=True, exist_ok=True)
    blobs = {s: serialise(ts) for s, ts in splits.items()}
    for s, b in blobs.items():
        split_path(s).write_bytes(b)
    manifest = build_manifest(splits, qa, blobs)
    MANIFEST.write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8", newline="\n"
    )
    write_review(splits["dev"])
    return manifest


# --- review file (dev only) ----------------------------------------------------------------------------


def pick_review(dev: list[Ticket], seed: int = G.SEED) -> list[Ticket]:
    """30 EN + 20 AR dev items, spread over tasks, levels and decisions."""
    rng = random.Random(f"{seed}:review")
    quota = {
        "en": {"faq": 5, "intent": 4, "extract": 4, "adjudicate": 17},
        "ar": {"faq": 3, "intent": 3, "extract": 3, "adjudicate": 11},
    }
    picked: list[Ticket] = []
    for lang, per_task in quota.items():
        for task, k in per_task.items():
            pool = [t for t in dev if t.language == lang and t.task_type == task]
            if task == "adjudicate":  # round-robin over decisions so every label is reviewed
                by_dec: dict[str, list[Ticket]] = {}
                for t in sorted(pool, key=lambda t: t.id):
                    by_dec.setdefault(t.gold.decision, []).append(t)
                for lst in by_dec.values():
                    rng.shuffle(lst)
                order = sorted(by_dec)
                while k and any(by_dec.values()):
                    for d in order:
                        if k and by_dec[d]:
                            picked.append(by_dec[d].pop())
                            k -= 1
            else:
                picked += rng.sample(sorted(pool, key=lambda t: t.id), k)
    return picked


def _trace_table(t: Ticket) -> list[str]:
    rows = ["| # | Rule | Check | Fired | Detail |", "|---|---|---|---|---|"]
    for i, s in enumerate(t.meta.trace, 1):
        rows.append(f"| {i} | {s.rule} | {s.check} | {'**yes**' if s.fired else 'no'} | {s.detail} |")
    return rows


def write_review(dev: list[Ticket]) -> None:
    items = pick_review(dev)
    n_en = sum(t.language == "en" for t in items)
    lines = [
        "# Phase 1 manual review — 30 EN + 20 AR dev items (SPEC §4.4)",
        "",
        "> FICTIONAL insurer and synthetic tickets. Rules follow SAMA-issued instruments; "
        "see data/rules/SOURCES.md.",
        "",
        f"Generated by `engine gen` (seed {G.SEED}). {n_en} EN + {len(items) - n_en} AR items from dev only; "
        "held-out is"
        " never shown. Gold comes only from the rules engine; the trace lists every rule checked, in order.",
        "Mark any label error below; any error means fix the generator and regenerate (SPEC §4.4).",
        "",
    ]
    for t in items:
        lines += [
            f"## {t.id} · {t.task_type} · {t.level} · {t.language}/{t.dialect} · `{t.template_family}`"
            f" · rules {t.rules_version}",
            "",
        ]
        if t.meta.design:
            lines.append(
                f"Design: `{t.meta.design}`"
                + (f" · rules exercised: {', '.join(t.meta.rule_ids)}" if t.meta.rule_ids else "")
            )
            lines.append("")
        lines += ["```text", t.text, "```", "", "**Gold:** `" + t.gold.model_dump_json() + "`", ""]
        if isinstance(t.gold, AdjudicateGold):
            lines += _trace_table(t) + [""]
        lines += ["Review: ☐ correct ☐ label error — note:", ""]
    REVIEW.parent.mkdir(parents=True, exist_ok=True)
    REVIEW.write_text("\n".join(lines), encoding="utf-8", newline="\n")
