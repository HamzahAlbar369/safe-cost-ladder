"""`engine report`: metrics.json -> reports/report.html (self-contained) + reports/figures/*.png + INDEX.md.

Presentation only: every number comes from reports/metrics.json (engine.report.collect), every chart from
engine.report.figures, every on-page number through the render helper (data-metric spans).
"""

from __future__ import annotations

import json
from pathlib import Path

import plotly.io as pio
from jinja2 import Environment, FileSystemLoader, StrictUndefined
from markupsafe import Markup

from engine.llm.pricing import ROOT
from engine.report import collect as C
from engine.report import figures as F
from engine.report import theme as T
from engine.report.render import Renderer

REPORTS = ROOT / "reports"
HTML = REPORTS / "report.html"
FIG_DIR = REPORTS / "figures"
TEMPLATES = Path(__file__).parent / "templates"


def figure_divs(m: dict) -> dict[str, Markup]:
    out = {}
    for f in F.FIGURES:
        fig = f.build(m, T.Size(png=False))
        fig.update_layout(height=f.html_height, autosize=True)
        spec = fig.to_json()
        out[f.name] = Markup(
            f'<div class="chart" id="fig-{f.name}" role="img" aria-label="{f.claim}"></div>'
            f'<script type="application/json" data-fig="fig-{f.name}">{spec}</script>'
        )
    return out


def write_pngs(m: dict, out: Path = FIG_DIR) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    figs, paths = [], []
    for f in F.FIGURES:
        figs.append(f.build(m, T.Size(png=True)))
        paths.append(out / f"{f.name}.png")
    pio.write_images(figs, paths, width=1920, height=1080, scale=2)
    return paths


def write_index(m: dict, out: Path = FIG_DIR) -> Path:
    p = m["provenance"]
    lines = [
        "# Figures",
        "",
        "Generated by `engine report` from `reports/metrics.json`; 1920x1080 at 2x. Do not edit by hand.",
        "",
        "| file | claim it supports | title (generated from the results) | source run(s) |",
        "|---|---|---|---|",
    ]
    for f in F.FIGURES:
        runs = " + ".join(p["runs"][k] for k in F.SOURCES[f.name])
        title = F.title_text(m, F.TITLES[f.name](m))
        lines.append(f"| `{f.name}.png` | {f.claim} | {title} | {runs} |")
    lines += [
        "",
        f"Build git SHA: {p['build_git_sha']}; held-out run at {p['heldout_tag']} ({p['heldout_git_sha']}).",
    ]
    path = out / "INDEX.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def render_html(m: dict) -> str:
    import plotly.offline

    r = Renderer(m)
    env = Environment(loader=FileSystemLoader(TEMPLATES), undefined=StrictUndefined, autoescape=True)

    def title(name: str) -> Markup:
        return r.title(F.TITLES[name](m))

    env.globals.update(m=r.m, ci=r.ci, v=r.v, prov=r.prov, title=title, T=T, tasks=F.TASKS)
    css = (TEMPLATES / "report.css").read_text("utf-8")
    return env.get_template("report.html.j2").render(
        css=Markup(T.css_vars() + css),
        figs=figure_divs(m),
        plotlyjs=Markup(plotly.offline.get_plotlyjs()),
        caption=lambda name: r.prov(F.caption(m, name)),
    )


def build(*, recollect: bool = True, png: bool = True, progress=print) -> list[Path]:
    m = C.collect(progress) if recollect else C.load()
    if recollect:
        C.write(m)
    HTML.write_text(render_html(m), encoding="utf-8")
    paths = [C.OUT, HTML]
    if png:
        progress("PNG figures ...")
        paths += write_pngs(m)
        paths.append(write_index(m))
    return paths


def metrics_keys_on_page(html: str) -> list[tuple[str, str, str]]:
    """(key, fmt, text) of every data-metric span (used by the integrity test)."""
    import re

    pat = r'<span class="num" data-metric="([^"]+)" data-fmt="([^"]+)">([^<]*)</span>'
    return [(k, f, t) for k, f, t in re.findall(pat, html)]


__all__ = ["build", "render_html", "metrics_keys_on_page", "json"]
