"""`engine report`: metrics.json -> reports/report.html (self-contained) + reports/figures/*.png + INDEX.md.

Presentation only: every number comes from reports/metrics.json (engine.report.collect), every chart from
engine.report.figures, every on-page number through the render helper (data-metric spans).
"""

from __future__ import annotations

import json
from pathlib import Path

import plotly.io as pio
from jinja2 import Environment, FileSystemLoader, StrictUndefined
from markupsafe import Markup

from engine.llm.pricing import ROOT
from engine.report import collect as C
from engine.report import figures as F
from engine.report import theme as T
from engine.report.render import Renderer

TASKS_ = F.TASKS

REPORTS = ROOT / "reports"
HTML = REPORTS / "report.html"
FIG_DIR = REPORTS / "figures"
TEMPLATES = Path(__file__).parent / "templates"


def figure_divs(m: dict) -> dict[str, Markup]:
    out = {}
    for f in F.FIGURES:
        fig = f.build(m, T.Size(png=False))
        fig.update_layout(height=f.html_height, autosize=True)
        spec = fig.to_json()
        out[f.name] = Markup(
            f'<div class="chart" id="fig-{f.name}" role="img" aria-label="{f.claim}"></div>'
            f'<script type="application/json" data-fig="fig-{f.name}">{spec}</script>'
        )
    return out


def write_pngs(m: dict, out: Path = FIG_DIR) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    figs, paths = [], []
    for f in F.FIGURES:
        figs.append(f.build(m, T.Size(png=True)))
        paths.append(out / f"{f.name}.png")
    pio.write_images(figs, paths, width=1920, height=1080, scale=2)
    return paths


def write_index(m: dict, out: Path = FIG_DIR) -> Path:
    p = m["provenance"]
    lines = [
        "# Figures",
        "",
        "Generated by `engine report` from `reports/metrics.json`; 1920x1080 at 2x. Do not edit by hand.",
        "",
        "| file | claim it supports | title (generated from the results) | source run(s) |",
        "|---|---|---|---|",
    ]
    for f in F.FIGURES:
        runs = " + ".join(p["runs"][k] for k in F.SOURCES[f.name])
        title = F.title_text(m, F.TITLES[f.name](m))
        lines.append(f"| `{f.name}.png` | {f.claim} | {title} | {runs} |")
    lines += [
        "",
        f"Build git SHA: {p['build_git_sha']}; held-out run at {p['heldout_tag']} ({p['heldout_git_sha']}).",
    ]
    path = out / "INDEX.md"
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path


def render_html(m: dict) -> str:
    import plotly.offline

    r = Renderer(m)
    env = Environment(loader=FileSystemLoader(TEMPLATES), undefined=StrictUndefined, autoescape=True)

    def title(name: str) -> Markup:
        return r.title(F.TITLES[name](m))

    env.globals.update(m=r.m, ci=r.ci, v=r.v, prov=r.prov, title=title, T=T, tasks=F.TASKS)
    css = (TEMPLATES / "report.css").read_text("utf-8")
    return env.get_template("report.html.j2").render(
        css=Markup(T.css_vars() + css),
        figs=figure_divs(m),
        plotlyjs=Markup(plotly.offline.get_plotlyjs()),
        caption=lambda name: r.prov(F.caption(m, name)),
    )


def build(*, recollect: bool = True, png: bool = True, progress=print) -> list[Path]:
    m = C.collect(progress) if recollect else C.load()
    if recollect:
        C.write(m)
    HTML.write_text(render_html(m), encoding="utf-8")
    paths = [C.OUT, HTML, update_readme(m)]
    if png:
        progress("PNG figures ...")
        paths += write_pngs(m)
        paths.append(write_index(m))
    return paths


README = ROOT / "README.md"
START, END = "<!-- results:start (generated by engine report; do not edit) -->", "<!-- results:end -->"


def readme_block(m: dict) -> str:
    """The README's results block, generated from metrics.json (no hand-typed figure)."""
    from engine.report.render import fmt_value as f

    H, S, D = (m["splits"][k]["policies"] for k in ("heldout", "shifted", "dev"))
    live, sim, p = H["O1_live"], H["O1"], m["provenance"]
    rows = [
        "| policy (held-out) | accuracy | success | p95 | CPST, "
        + T.HEADLINE
        + " | CPST, "
        + T.CACHED
        + " | floors |",
        "|---|---:|---:|---:|---:|---:|---|",
    ]
    names = {"B1": "B1 always-best", "B2": "B2 always-cheapest", "B3": "B3 static per task", "O1": "O1 (simulated)",
             "O1_live": "**O1 (live)**", "Oracle": "Oracle (cheapest correct config per ticket)"}  # fmt: skip
    for k, name in names.items():
        e = H[k]
        ci = f" [{f(e['cpst_nocache_lo'], 'usd5')}, {f(e['cpst_nocache_hi'], 'usd5')}]"
        rows.append(f"| {name} | {f(e['acc'], 'f3')} | {f(e['success'], 'f3')} | {f(e['p95_s'], 's2')} | "
                    f"{f(e['cpst_nocache'], 'usd5')}{ci} | {f(e['cpst_cached'], 'usd5')} | "
                    f"{'met' if e['meets_floors'] else 'BREACH'} |")  # fmt: skip
    over = [t for t in TASKS_ if live["per_task"][t]["p95_s"] > m["floors"][t]["budget_s"]]
    b2_dev, b2_shift = D["B2"]["meets_floors"], S["B2"]["meets_floors"]
    lines = [
        START,
        f"**Held-out** ({m['splits']['heldout']['n']} sealed tickets, evaluated once at `{p['heldout_tag']}`): O1 "
        f"{T.LIVE} costs **{f(live['saving_nocache'], 'pct1')} less per successful task** than always-best (B1), "
        f"95% CI [{f(live['saving_nocache_lo'], 'pct1')}, {f(live['saving_nocache_hi'], 'pct1')}] "
        f"({T.HEADLINE}); {f(live['saving_cached'], 'pct1')} on {T.CACHED}. Every per-task accuracy floor is "
        + ("met." if live["meets_floors"] else "NOT met."),
        "",
        *rows,
        "",
        f"- **Always-cheapest beat O1 on held-out.** B2 ({m['o1_config']['first']} for everything) "
        f"{'met every floor' if H['B2']['meets_floors'] else 'breached a floor'} on held-out at CPST "
        f"{f(H['B2']['cpst_nocache'], 'usd5')} vs O1 {T.LIVE} {f(live['cpst_nocache'], 'usd5')}, but it "
        f"{'breached' if not b2_dev else 'met'} the floors on dev (accuracy {f(D['B2']['acc'], 'f3')}), where policies "
        f"were chosen, and {'breached' if not b2_shift else 'met'} them on shifted (accuracy {f(S['B2']['acc'], 'f3')}).",
        f"- **{T.SIMULATED.capitalize()} vs {T.LIVE} latency gap.** {T.LIVE.capitalize()} p95 {f(live['p95_s'], 's2')} "
        f"vs {f(sim['p95_s'], 's2')} {T.SIMULATED}; success {f(live['success'], 'f3')} vs {f(sim['success'], 'f3')}"
        + (
            "; "
            + ", ".join(
                f"{t} ran over its latency budget {T.LIVE} (p95 {f(live['per_task'][t]['p95_s'], 's2')} "
                f"vs {f(m['floors'][t]['budget_s'], 's1')})"
                for t in over
            )
            if over
            else ""
        )  # fmt: skip
        + f". Correctness agreed on {m['splits']['heldout']['sim_vs_live']['same_correct']} of "
        f"{m['splits']['heldout']['sim_vs_live']['n']} tickets.",
        f"- **Shifted traffic** ({T.SIMULATED}): O1 still costs {f(S['O1']['saving_nocache'], 'pct1')} less than B1, but "
        f"accuracy {f(S['O1']['acc'], 'f3')} vs B1 {f(S['B1']['acc'], 'f3')}; floors breached: "
        + (", ".join(t for t in TASKS_ if not S["O1"]["per_task"][t]["meets_floor"]) or "none")
        + f". Fail-safe analysis (added after observing shifted): accuracy "
        f"{f(m['splits']['shifted']['analysis']['failsafe']['acc'], 'f3')}.",
        "",
        f"Source: `reports/metrics.json` (runs {', '.join(p['runs'].values())}; built at git "
        f"`{p['build_git_sha'][:12]}`). Full report: `reports/report.html`.",
        END,
    ]
    return "\n".join(lines)


def update_readme(m: dict, path: Path = README) -> Path:
    text = path.read_text("utf-8")
    a, b = text.index(START), text.index(END) + len(END)
    path.write_text(text[:a] + readme_block(m) + text[b:], encoding="utf-8")
    return path


def metrics_keys_on_page(html: str) -> list[tuple[str, str, str]]:
    """(key, fmt, text) of every data-metric span (used by the integrity test)."""
    import re

    pat = r'<span class="num" data-metric="([^"]+)" data-fmt="([^"]+)">([^<]*)</span>'
    return [(k, f, t) for k, f, t in re.findall(pat, html)]


